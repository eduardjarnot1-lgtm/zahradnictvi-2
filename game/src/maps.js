// The seven hand-drawn floorplans, recreated tile for tile from their reference
// drawings. Each grid below *is* the map: what you can read here is the shape of
// the building, at exactly the proportions the drawing was made at.
//
// See tilemap.js for what every character means. The short version:
//   #  outer wall    %  interior wall   O  window    D  doorway
//   .  floor         ,  rug (silent)    ~  creaky boards
//   E  the sleeper's own furniture      @  spawn     X  the way out
//   T table   S sofa or bed   W wardrobe   N nightstand   V tv bench
//   C cabinet   B shelving    P display plinth
// Everything else is loot, per LOOT below.
//
// The grids are drafted rather than typed: a doorway needs two clear tiles
// behind it (a player is taller than one tile), and furniture that would seal a
// room is trimmed back to leave the landing.
